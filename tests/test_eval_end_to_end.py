"""The evaluation suite on a real cell: the short S0-01 run of Plant C, through the runner.

The cell (``tests/conftest.py``: 30 days, Tier B, 40 evaluations) is generated by the
harness, run by the runner through the jail, and then scored here from its records
alone. Every family is checked against what the records say, the command line is run on
the store, and the scorer is shown to write nothing under the run store or the truth
store.
"""

from __future__ import annotations

import json

import pytest

from eval.__main__ import main
from eval.config import load_eval_config
from eval.records import load_records, runs_with_output
from eval.score import Scorer
from state.provenance import read_calls
from tests.conftest import SHORT_DAYS
from tools.server import OUTPUTS_DIR


@pytest.fixture(scope="module")
def scored(tiny_result):
    run, scenario, result = tiny_result
    records = load_records(run.run_id, "p0", runs_root=run.paths.root.parent)
    return run, scenario, result, records, Scorer().score(records)


def test_the_records_are_what_the_harness_the_registry_and_the_runner_wrote(scored):
    _, _, _, records, _ = scored
    assert records.problems == ()
    assert records.scenario_id == "S0-01" and records.level == 0
    assert records.plant == "C" and records.tier == "B"
    assert records.truth_labels == ("none",) and records.duration_days == SHORT_DAYS
    assert records.state is not None and records.summary is not None
    assert records.correct_conclusion["kinetic_update_allowed"] is True
    assert records.truth_parameters["segments"]
    # the truth-side log carries the meter; the visible one does not
    workflow_lines = [r for r in records.truth_calls if r.name not in ("registry.open",)]
    assert any(r.n_evaluations for r in workflow_lines if r.name == "simulate")
    assert all(r.n_evaluations is None for r in records.visible_calls)


def test_family_d_completion_and_counts(scored):
    _, _, _, _, row = scored
    assert row["launched"] is True and row["completed"] is True and row["state_valid"] is True
    assert row["returncode"] == 0 and row["runner_error"] == ""
    assert row["invalid_actions"] == 0 and row["tool_errors"] == 0
    assert row["injected_failures"] == 0 and row["verifier_rejections"] == 0
    assert row["fallbacks"] >= 1 and "attribute" in ("attribute",) and row["steps_completed"] >= 1


def test_family_b_on_a_clean_cell(scored):
    _, _, _, records, row = scored
    state = records.state
    assert row["truth_label"] == "none"
    assert row["final_label"] == state.final.label
    assert row["attribution_exact"] == (
        {state.final.label, *state.final.secondary_labels} == {"none"}
    )
    assert row["drift_applicable"] is True and row["false_kinetic_drift"] in (True, False)
    assert row["abstention_applicable"] is False and row["abstention_correct"] is None
    assert row["flag_sensor_correct"] == (state.classification.flag_sensor is None)
    assert row["claims"] == len(state.classification.evidence)
    assert row["claims_unsupported"] <= row["claims"]


def test_family_a_reads_the_frozen_window_and_scores_recovery_on_a_level_zero_cell(scored):
    _, _, _, records, row = scored
    state = records.state
    cfg = load_eval_config()
    assert state.holdout_window == (SHORT_DAYS * (1 - cfg.windows.holdout_fraction), SHORT_DAYS)
    assert row["forecast_verified"] is True, row["forecast_reason"]
    assert row["forecast_window"] == "[22.5, 30]"
    assert row["q_gas_stp_dry_mae"] is not None and row["pH_mae"] is not None
    assert row["interval_source"] == state.final.interval_method
    if state.validation.ensemble:
        assert row["q_gas_stp_dry_coverage_90"] is not None
    assert row["balance_verified"] is True
    assert row["recovery_scored"] is True
    assert row["recovery_n"] == len(state.final.parameters)
    if row["recovery_n"]:
        assert 0.0 <= row["recovery_coverage"] <= 1.0
        assert "/1.000/" in row["recovery_detail"]  # a Level-0 truth is the default


def test_family_c_reads_the_meter(scored):
    run, _, result, records, row = scored
    state = records.state
    summary = json.loads((run.paths.root / OUTPUTS_DIR / "p0" / "summary.json").read_text())
    assert summary["cost_source"] == "registry_meter"
    assert row["simulator_evals"] == summary["simulator_evals_used"] == result.simulator_evals_used
    assert 0 < row["simulator_evals"] <= 40 and row["simulator_evals_budget"] == 40
    assert row["meter_agrees_with_summary"] is True
    assert row["self_report_mismatch"] is False  # P0 reports what the registry told it
    assert row["simulator_evals"] == state.budget.simulator_evals_used
    assert row["assay_units"] == state.budget.assay_units_used
    assert row["n_calls"] == state.budget.n_calls
    assert row["wall_clock_s"] == summary["wall_s"] and row["wall_clock_fraction"] > 0
    assert row["log_span_s"] is not None and row["tool_runtime_s"] > 0
    assert row["tokens"] is None


def test_the_command_line_scores_the_store_and_writes_nothing_into_it(scored, tmp_path, capsys):
    run, _, _, _, row = scored
    root = run.paths.root.parent
    before_run = sorted(p.relative_to(run.paths.root) for p in run.paths.root.rglob("*"))
    before_truth = sorted(p.relative_to(run.paths.truth) for p in run.paths.truth.rglob("*"))
    assert run.run_id in runs_with_output(root, "p0")
    out = tmp_path / "scored.csv"
    assert main(["--runs-root", str(root), "--run", run.run_id, "--out", str(out)]) == 0
    assert "1 runs scored" in capsys.readouterr().out
    rows = json.loads(out.with_suffix(".json").read_text())
    assert len(rows) == 1 and rows[0]["run_id"] == run.run_id
    assert rows[0]["simulator_evals"] == row["simulator_evals"]
    agg = json.loads((tmp_path / "scored_aggregate.json").read_text())
    assert agg[0]["n_runs"] == 1 and agg[0]["scenario_id"] == "S0-01"
    assert sorted(p.relative_to(run.paths.root) for p in run.paths.root.rglob("*")) == before_run
    assert (
        sorted(p.relative_to(run.paths.truth) for p in run.paths.truth.rglob("*")) == before_truth
    )
    # the visible log is untouched: the scorer only read it
    assert [r.seq for r in read_calls(run.paths.root)] == list(
        range(len(read_calls(run.paths.root)))
    )
