def test_no_public_attribute_of_the_view_hands_over_a_path(generated_run):
    """The other live bypass: ``view.root / "truth" / "parameters.json"``.

    It wrote no forbidden string, so the static checker was blind to it. The rule that
    kills the whole class is that the view returns *contents*, never a path or a directory
    handle — so this walks every public attribute and no-argument method of the object and
    asserts none of them yields one.
    """
    from state.run_view import open_run

    view = open_run(generated_run.paths.root)
    public = [n for n in dir(view) if not n.startswith("_")]
    assert public, "the view exposes nothing at all, which would make this vacuous"

    checked = 0
    for name in public:
        value = getattr(view, name)
        if callable(value):
            try:
                value = value()
            except TypeError:  # takes arguments (e.g. read_text, sensor)
                continue
        checked += 1
        assert not isinstance(value, Path), f"view.{name} returns a Path"
        assert not any(isinstance(v, Path) for v in _leaves(value)), f"view.{name} yields a Path"
    assert checked >= 5, f"only {checked} accessors exercised"


def test_the_run_root_is_not_an_attribute_of_the_view(generated_run):
    """The lead's ruling E: the root is in a closure, not on the object.

    The review's live bypass was a *public* field. Making it private would have left the
    same object graph one underscore away, so there is no attribute at all — not `root`,
    not `_root`, and nothing whose value is the run directory or the observations
    directory.
    """
    from state.run_view import open_run

    view = open_run(generated_run.paths.root)
    for name in ("root", "_root", "_base", "path", "_resolve"):
        assert not hasattr(view, name), name

    # nothing stored on the object IS a path, under any name
    stored = {**getattr(view, "__dict__", {})}
    for field in getattr(view, "__dataclass_fields__", {}):
        stored[field] = getattr(view, field)
    for name, value in stored.items():
        assert not isinstance(value, Path | str), (name, value)

    # and the run directory does not appear as a value anywhere on it
    forbidden = {str(generated_run.paths.root), str(generated_run.paths.observations)}
    assert not forbidden & {str(v) for v in stored.values()}


def test_the_listing_and_the_resolver_agree(generated_run):
    """The lead's ruling E: `files` must not advertise what `read_text` will refuse.

    A planted symlink out of the tree used to be listed and then refused, so the view
    promised something it would not hand over.
    """
    from state.run_view import TruthAccessError, open_run

    link = generated_run.paths.observations / "planted.json"
    try:
        link.symlink_to(generated_run.paths.truth_faults)
    except (OSError, NotImplementedError):  # pragma: no cover - platform without symlinks
        pytest.skip("symlinks unavailable")
    try:
        view = open_run(generated_run.paths.root)
        assert "planted.json" not in view.files
        with pytest.raises(TruthAccessError):
            view.read_text("planted.json")
        # every listed file really is readable — the listing is not empty either
        assert view.files
        for name in view.files:
            assert view.read_text(name) is not None
    finally:
        link.unlink()


def _leaves(value: object, depth: int = 0) -> list[object]:
    """Every scalar reachable inside a returned container, to a bounded depth."""
    if depth > 3:
        return [value]
    if isinstance(value, dict):
        return [leaf for v in value.values() for leaf in _leaves(v, depth + 1)]
    if isinstance(value, list | tuple | set):
        return [leaf for v in value for leaf in _leaves(v, depth + 1)]
    return [value]


def test_a_symlink_out_of_the_observations_does_not_open_a_door(generated_run):
    """Resolution happens before the containment check, so a link is not an escape."""
    from state.run_view import TruthAccessError, open_run

    link = generated_run.paths.observations / "shortcut"
    try:
        link.symlink_to(generated_run.paths.truth, target_is_directory=True)
    except (OSError, NotImplementedError):  # pragma: no cover - platform without symlinks
        pytest.skip("symlinks unavailable")
    try:
        view = open_run(generated_run.paths.root)
        with pytest.raises(TruthAccessError):
            view.read_text("shortcut/faults.json")
        # and a link to a single file, which needs no directory traversal at all
        file_link = generated_run.paths.observations / "answers.json"
        file_link.symlink_to(generated_run.paths.truth_faults)
        try:
            with pytest.raises(TruthAccessError):
                view.read_text("answers.json")
        finally:
            file_link.unlink()
    finally:
        link.unlink()


