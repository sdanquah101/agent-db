"""Enforce CLAUDE.md rule 1: hidden truth is never readable by workflows.

Ground truth is written only to ``truth_store/<id>/`` — a separate top-level tree, not a
subdirectory of the run (the lead's ruling of 2026-09-04). The rule is enforced three times
over, because each layer alone is weak in a way the next one covers:

**Structurally.** ``runs/<id>/`` holds the observations, the redacted manifest and the call
log, and nothing else. A workflow rooted there has nothing to escape *to*. This is the
layer the review's two bypasses would have hit: it does not depend on the loader being
right, which is exactly why it is first.

**Statically.** Nothing under ``workflows/`` may import a ``truth``/``truth_store`` module
or reference a path with either as a segment. The check is AST-based, so it covers code
that is never executed in tests. Its blind spot is a path assembled at run time — and,
as the review showed, an attribute handed out by an API, which spells nothing at all.

**On the real API.** The last part of this file drives :func:`state.run_view.open_run` —
the loader a workflow actually uses — against a run generated by the harness, and asks it
for hidden truth in every way a caller could: by relative path, by traversal, by ``"."``
and ``""``, by absolute path, by symlink, by listing, by every public attribute and method
the object exposes, by looking for the run root anywhere on the object at all (it is in a
closure, not an attribute), and by reading the manifest fields that would give the answer
away.
All of it fails; the same run's truth is shown to be on disk and readable by anything that
is not the loader; and a **negative control** asserts that a legitimate read still
succeeds, so the test cannot pass by refusing everything.

The checker is exercised against synthetic violating and clean files first, so the static
half cannot pass simply because ``workflows/`` is still mostly empty.
"""

from __future__ import annotations

import ast
import json
import re
from dataclasses import dataclass
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
WORKFLOWS_DIR = REPO_ROOT / "workflows"

# A path-like string literal with "truth" or "truth_store" as a segment: "runs/x/truth/",
# "/truth", "truth_store/params.json", or the bare segment (as in Path(run) / "truth").
_TRUTH_PATH = re.compile(r"(?i)(^|[/\\])truth(_store)?([/\\]|$)")

_TRUTH_MODULES = frozenset({"truth", "truth_store"})


@dataclass(frozen=True)
class Violation:
    """One forbidden reference to hidden truth."""

    path: Path
    line: int
    kind: str
    detail: str

    def __str__(self) -> str:
        """Format as file:line: kind: detail."""
        return f"{self.path}:{self.line}: {self.kind}: {self.detail}"


def _docstring_nodes(tree: ast.AST) -> set[int]:
    """Return ids of string constants that are docstrings, which are exempt."""
    exempt: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                exempt.add(id(body[0].value))
    return exempt


def find_truth_references(path: Path) -> list[Violation]:
    """Statically find imports of, or path references to, hidden truth in one module.

    Args:
        path: A Python source file.

    Returns:
        Every violation found, in source order.
    """
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    exempt = _docstring_nodes(tree)
    found: list[Violation] = []

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if _TRUTH_MODULES & set(alias.name.lower().split(".")):
                    found.append(Violation(path, node.lineno, "import", alias.name))
        elif isinstance(node, ast.ImportFrom):
            module = (node.module or "").lower()
            segments = set(module.split(".")) if module else set()
            names = {alias.name.lower() for alias in node.names}
            if _TRUTH_MODULES & (segments | names):
                names_str = ", ".join(alias.name for alias in node.names)
                found.append(
                    Violation(path, node.lineno, "import", f"from {node.module} import {names_str}")
                )
        elif (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and id(node) not in exempt
            and _TRUTH_PATH.search(node.value)
        ):
            found.append(Violation(path, node.lineno, "path literal", repr(node.value)))

    return found


def workflow_modules() -> list[Path]:
    """Every Python module under workflows/, recursively."""
    return sorted(WORKFLOWS_DIR.rglob("*.py"))


# --- self-check: the checker must catch each forbidden pattern -----------------------

_VIOLATING_SOURCE = '''
"""Docstring mentioning runs/<id>/truth/ is allowed."""
import sim.truth
from sim import truth
from sim.truth.model import TruthModel
from sim.truth_store import load_truth
from pathlib import Path

def load(run: Path):
    a = open(run / "truth" / "params.json")
    b = open(f"{run}/truth/labels.json")
    c = open("/data/runs/abc/TRUTH/x.yaml")
    d = run.joinpath("truth")
    e = open("truth_store/run_abc/parameters.json")
    return a, b, c, d, e
'''

_CLEAN_SOURCE = '''
"""Ground truth is discussed here in a docstring only; that is fine."""
from pathlib import Path

from tools import registry

def load(run: Path):
    # "truthful" and "untruth" are not path segments and must not be flagged.
    label = "truthful"
    obs = open(run / "observations.csv")
    return registry, label, obs, "untruth"
'''


def test_checker_catches_every_forbidden_pattern(tmp_path: Path):
    bad = tmp_path / "bad_workflow.py"
    bad.write_text(_VIOLATING_SOURCE, encoding="utf-8")
    kinds = [v.kind for v in find_truth_references(bad)]
    assert kinds.count("import") == 4, kinds
    # "truth" (joined), "/truth/" (f-string part), "/TRUTH/", "truth" (joinpath),
    # "truth_store/..." (the tree hidden truth actually lives in)
    assert kinds.count("path literal") == 5, kinds


def test_checker_ignores_docstrings_and_near_misses(tmp_path: Path):
    good = tmp_path / "good_workflow.py"
    good.write_text(_CLEAN_SOURCE, encoding="utf-8")
    assert find_truth_references(good) == []


