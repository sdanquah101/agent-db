def test_the_manifest_a_workflow_sees_has_no_field_for_the_answer(generated_run):
    """The truth store's manifest carries the scenario, the seeds and the fault layers.

    The projection has no field for any of them — not even one that happens to be absent
    from this particular file, which is why ``hasattr`` is asserted as well as membership.
    """
    from sim.run.manifest import REDACTED_FIELDS
    from state.run_view import open_run

    complete = json.loads(generated_run.paths.truth_manifest.read_text(encoding="utf-8"))
    assert set(complete) >= REDACTED_FIELDS, "the stored manifest is supposed to be complete"

    public = open_run(generated_run.paths.root).manifest
    dumped = public.model_dump()
    for field in REDACTED_FIELDS:
        assert field not in dumped, field
        assert not hasattr(public, field), field
    # and no seed value has leaked into it under another name. `replicate` is excluded:
    # it is an index, not a secret, and its value 0 collides with every other zero.
    from sim.run.seeds import STREAM_ORDER

    secret = {str(complete["seeds"][name]) for name in (*STREAM_ORDER, "base")}
    assert not secret & {str(v) for v in dumped.values()}


